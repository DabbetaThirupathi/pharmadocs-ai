"""SQLite persistence layer for PharmaDocs AI.

Tables
------
users        : application users with role + department scope
documents    : controlled documents (SOPs, policies) with version & lifecycle status
chunks       : section-level chunks used for retrieval
audit_log    : append-only, hash-chained audit trail (21 CFR Part 11 inspired)
deviations   : deviation report drafts generated by the assistant
"""
import sqlite3
from flask import current_app, g

SCHEMA = """
CREATE TABLE IF NOT EXISTS users (
    id            INTEGER PRIMARY KEY AUTOINCREMENT,
    username      TEXT UNIQUE NOT NULL,
    full_name     TEXT NOT NULL,
    password_hash TEXT NOT NULL,
    role          TEXT NOT NULL CHECK (role IN ('OPERATOR','PRODUCTION','QA','ADMIN')),
    department    TEXT NOT NULL,
    is_active     INTEGER NOT NULL DEFAULT 1,
    created_at    TEXT NOT NULL DEFAULT (datetime('now'))
);

CREATE TABLE IF NOT EXISTS documents (
    id             INTEGER PRIMARY KEY AUTOINCREMENT,
    doc_number     TEXT NOT NULL,
    title          TEXT NOT NULL,
    version        INTEGER NOT NULL,
    department     TEXT NOT NULL,
    doc_type       TEXT NOT NULL DEFAULT 'SOP',
    status         TEXT NOT NULL CHECK (status IN ('DRAFT','EFFECTIVE','OBSOLETE')),
    access_level   TEXT NOT NULL DEFAULT 'ALL',   -- ALL | QA_ONLY | RESTRICTED
    effective_date TEXT,
    checksum       TEXT NOT NULL,
    source_file    TEXT,
    uploaded_by    INTEGER REFERENCES users(id),
    uploaded_at    TEXT NOT NULL DEFAULT (datetime('now')),
    UNIQUE (doc_number, version)
);

CREATE TABLE IF NOT EXISTS chunks (
    id          INTEGER PRIMARY KEY AUTOINCREMENT,
    document_id INTEGER NOT NULL REFERENCES documents(id) ON DELETE CASCADE,
    section     TEXT NOT NULL,
    ordinal     INTEGER NOT NULL,
    text        TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS audit_log (
    id          INTEGER PRIMARY KEY AUTOINCREMENT,
    ts          TEXT NOT NULL,
    user_id     INTEGER,
    username    TEXT,
    action      TEXT NOT NULL,
    entity      TEXT,
    entity_id   TEXT,
    details     TEXT,
    prev_hash   TEXT NOT NULL,
    entry_hash  TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS deviations (
    id            INTEGER PRIMARY KEY AUTOINCREMENT,
    dev_number    TEXT UNIQUE NOT NULL,
    created_by    INTEGER REFERENCES users(id),
    created_at    TEXT NOT NULL DEFAULT (datetime('now')),
    area          TEXT,
    classification TEXT,
    description   TEXT NOT NULL,
    report_json   TEXT NOT NULL,
    status        TEXT NOT NULL DEFAULT 'DRAFT'
);

-- The audit trail must never be edited or deleted.
CREATE TRIGGER IF NOT EXISTS audit_no_update
BEFORE UPDATE ON audit_log
BEGIN SELECT RAISE(ABORT, 'audit_log is append-only'); END;

CREATE TRIGGER IF NOT EXISTS audit_no_delete
BEFORE DELETE ON audit_log
BEGIN SELECT RAISE(ABORT, 'audit_log is append-only'); END;
"""


def connect(path: str) -> sqlite3.Connection:
    conn = sqlite3.connect(path, detect_types=sqlite3.PARSE_DECLTYPES)
    conn.row_factory = sqlite3.Row
    conn.execute("PRAGMA foreign_keys = ON")
    return conn


def get_db() -> sqlite3.Connection:
    if "db" not in g:
        g.db = connect(current_app.config["DATABASE"])
    return g.db


def close_db(_exc=None):
    db = g.pop("db", None)
    if db is not None:
        db.close()


def init_schema(conn: sqlite3.Connection):
    conn.executescript(SCHEMA)
    conn.commit()
